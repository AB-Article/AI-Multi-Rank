#!/usr/bin/env python3
"""Generate the demo inputs for select_model.py, from a KNOWN truth.

The truth is the cure chart of Prop. `cure`,

    eps(x) = exp{-lambda (1 - e^{-c(x - x0)})},   eps_inf = e^{-lambda},

for which the canonical price at grain 1 is exactly `c` and N_eff = Delta S
identically.  Two calibration curves are written from the same truth and the
same number of test items, differing only in the WIDTH of the geometric grid:

    calibration.csv       6 points, step x2 ... kappa is below the noise
    calibration_wide.csv  6 points, step x4 ... kappa is above it

That contrast is the point.  kappa is read as a second difference, whose signal
grows as h^2 while its noise does not, so widening the grid is quadratically
cheaper than buying test items -- and it is the difference between a price that
is identified and one that is not.

Stdlib only.  Deterministic: the binomial noise is drawn from a fixed seed.
"""
import csv
import math
import os
import random
import statistics

LAM, C, X0, Q0 = 5.0083, 0.4482, 0.0, 0.1
HERE = os.path.dirname(os.path.abspath(__file__))


def eps_true(x):
    return math.exp(-LAM * (1.0 - math.exp(-C * (x - X0))))


def observe(x, n, rng):
    """Draw an observed accuracy from n test items at the true eps."""
    e = eps_true(x) * (1.0 - Q0)              # true raw error rate
    k = sum(1 for _ in range(0) )             # placeholder, see below
    # binomial(n, e) by normal approximation with an exact-ish integer count
    mu, sd = n * e, math.sqrt(n * e * (1.0 - e))
    k = max(1, min(n - 1, int(round(rng.gauss(mu, sd)))))
    return 1.0 - k / n, k


def write(path, rows, header, note):
    with open(os.path.join(HERE, path), "w", newline="") as fh:
        fh.write(note)
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    print(f"  -> {path}")


def main():
    rng = random.Random(20261008)

    # ---- the two calibration curves, same items, different grid width.
    #      The wide one has SEVEN points, because the O(h^2) bias correction of
    #      F16 reads the plane on the 2h grid as well and needs four points
    #      there; with six it is refused, which the tool says.
    for name, ratio, n, K in (("calibration.csv", 2.0, 10_000, 6),
                              ("calibration_wide.csv", 4.0, 100_000, 7)):
        t0 = 8.0 if ratio == 2.0 else 2.0
        rows = []
        for i in range(K):
            t = t0 * ratio ** i
            q, _ = observe(math.log(t), n, rng)
            rows.append([f"base@{i+1}", f"{q:.6f}", f"{t:g}", n])
        write(name, rows, ["name", "accuracy", "inference_time", "n_test"],
              f"# ONE model re-run at {K} inference budgets, step x{ratio:g},"
              f" {n} test items.\n"
              f"# Generated by make_demo_data.py from the cure chart"
              f" (lambda={LAM}, c={C}): the canonical price is exactly"
              f" {C} nats/e-fold.\n")

    # ---- the candidate zoo, AND the per-item outcomes it was scored on.
    #      The two must agree exactly, so the accuracies are counted from the
    #      items rather than drawn separately: that is the whole point of F11
    #      and F12, which read the pair's own 2x2 table.
    #
    #      Item k has a shared latent difficulty z_k, and candidate i fails it
    #      when  sqrt(w) z_k + sqrt(1-w) xi_ik > c_i,  with c_i fixed by the
    #      true error rate of that candidate.  The combination is standard
    #      normal, so every marginal error rate is exactly the truth, while w
    #      sets how strongly the candidates fail the SAME items -- which is the
    #      covariance the unpaired band throws away.  The archive's own panel
    #      measures a failure correlation of 0.50 over all pairs and 0.77 over
    #      adjacent ones; w = 0.9 on the latent scale puts the demo in that range.
    N_ITEMS, W = 20_000, 0.9
    zoo = (("tiny", 5), ("small", 12), ("base", 30),
           ("large", 75), ("huge", 180))
    nd = statistics.NormalDist()
    thr = {}
    for nm, t in zoo:
        e_raw = eps_true(math.log(t)) * (1.0 - Q0)
        thr[nm] = nd.inv_cdf(1.0 - e_raw)
    rng_i = random.Random(777)
    sw, sw1 = math.sqrt(W), math.sqrt(1.0 - W)
    correct = {nm: [] for nm, _ in zoo}
    for _ in range(N_ITEMS):
        z = rng_i.gauss(0.0, 1.0)
        for nm, _t in zoo:
            v = sw * z + sw1 * rng_i.gauss(0.0, 1.0)
            correct[nm].append(0 if v > thr[nm] else 1)
    names = [nm for nm, _ in zoo]
    with open(os.path.join(HERE, "items_demo.csv"), "w", newline="") as fh:
        fh.write("# Per-item outcomes on the SHARED test set: 1 = correct.\n"
                 "# This file is what turns the verdict into a certified set"
                 " (F11, F12):\n"
                 "# the pair's own 2x2 table gives the paired variance of the"
                 " gap and the\n"
                 "# distribution-free exclusion certificate, with no new input"
                 " parameter.\n")
        w = csv.writer(fh)
        w.writerow(names)
        for k in range(N_ITEMS):
            w.writerow([correct[nm][k] for nm in names])
    print("  -> items_demo.csv")

    rows = []
    for nm, t in zoo:
        q = sum(correct[nm]) / float(N_ITEMS)      # counted, not drawn
        params = 1.1 * t ** 0.85                   # a correlated second axis
        rows.append([nm, f"{q:.6f}", f"{t:g}", f"{params:.2f}", N_ITEMS])
    write("models.csv", rows,
          ["name", "accuracy", "inference_time", "param_count", "n_test"],
          "# Candidate models, each evaluated once on the same test set.\n"
          "# Two resources: inference_time (priced from the calibration curve)"
          " and param_count (priced by declaration).\n"
          "# The accuracies are COUNTED from items_demo.csv, so the two files"
          " agree exactly.\n")

    # ---- a count axis: a nested pass@k curve, as the co-failure panel measures
    #      P(k) = probability an item is still failed after k attempts.
    #      Nested difficulty: Pr[both fail] = kappa min(h_i, h_j), kappa = 0.835
    #      (the measured law; independence is refuted at 19 standard errors).
    rows = []
    P1 = 0.18
    for k in range(1, 13):
        # a Beta-mixture of per-item failure probabilities reproduces the
        # measured discount D(2) ~ 0.52 far better than independence
        a, b = 0.55, 0.55 * (1.0 - P1) / P1
        s = 0.0
        M = 4000
        for i in range(M):
            u = (i + 0.5) / M
            # inverse-cdf-free: quadrature on the Beta(a,b) density
            dens = u ** (a - 1) * (1 - u) ** (b - 1)
            s += dens * u ** k
        z = 0.0
        for i in range(M):
            u = (i + 0.5) / M
            z += u ** (a - 1) * (1 - u) ** (b - 1)
        rows.append([k, f"{s / z:.8f}"])
    write("passk_demo.csv", rows, ["k", "P"],
          "# A count axis: P(k) = probability an item is still failed after k\n"
          "# independent attempts.  On this axis the axiom is a THEOREM of\n"
          "# exchangeability and the floor is bracketed by measured numbers.\n")


if __name__ == "__main__":
    main()
