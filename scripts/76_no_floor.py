#!/usr/bin/env python3
"""THE FLOOR IS NOT A PARAMETER.  eps_inf and the shape index beta are one
   degree of freedom.  (Section "The floor is not a parameter" of paper.tex.)

Script 75 put the floor in closed local form, eps_inf = kappa eps/(s^2+kappa).
This script shows that the floor and the shape index of script 69 are the same
degree of freedom, and that the measured floor share is what a frontier with NO
floor produces.

For a spectrum regularly varying at the origin -- eps = exp(-(alpha u)^beta),
the Laplace transform of a one-sided stable density of index beta, which is the
law script 69 fits and script 71 identifies as the per-skill tail index -- the
local calculus gives an EXACT identity with no floor anywhere in it:

    T1   p_0 = (1 - beta) / ((1 - beta) + beta S) ,   S = -ln eps
         <=>  beta = s^2 / (s^2 + kappa S)      [origin-free, floor-free]

Read in both directions:
  beta = 1  =>  p_0 == 0        : no floor at all
  beta -> 0 =>  p_0 -> 1        : the frontier reads as all floor
  S -> inf  =>  p_0 -> 0        : no asymptotic floor on any beta > 0 frontier,
                                  with the exact running rate p_0 ~ (1-beta)/(beta S).

Hence:

    T2   a two-atom fit to a frontier whose floor is EXACTLY ZERO returns a
         floor equal to a large fraction of the best observed error, monotone
         in beta.  At beta = 0.6 that fraction is ~0.51 -- the value the
         archive measures (table_floor_free_summary: median floor share 0.51).
         The measured floor share is therefore a readout of beta and carries
         no evidence of a floor.

    T3   exactly one shape parameter is identified.  Head-to-head held-out
         comparison on every single-resource frontier:
             floorless shape law   S = A (x-x0)^beta           (3 par.)
             two-atom with floor   eps = einf + c e^{-a x}     (3 par.)
             both                  eps = einf + c e^{-(a(x-x0))^beta}  (4 par.)
         The fourth parameter buys essentially nothing.

    T4   the two 3-parameter charts are mutually indistinguishable at the
         measurement noise: each fits data generated by the other to ~0.02-0.03
         nats, which is the noise level of the corpora.

    T5   the canonical point is a DEPTH IN NATS set by beta alone,
             S* = (1 - beta)/beta ,   eps* = exp(1 - 1/beta) ,
         with no alpha, no floor, no units and no resource measurement.  With
         the corpus betas of T3 this lands in the error band in which
         benchmarks are published, which is why the measured windows straddle
         the crossover.

Reads  results/frontiers/*.csv   (built by 01_build_frontiers.py / 07_new_corpora.py)
Writes (results/):
    table_no_floor_identity.csv   T1, exactness grid
    table_no_floor_null.csv       T2, the zero-floor null for the floor share
    table_one_dof_holdout.csv     T3, per-frontier held-out errors
    table_one_dof_summary.csv     T3, the summary table quoted in the paper
    table_crossfit.csv            T4
    table_knee_depth.csv          T5
"""
from __future__ import annotations
import os
import glob
import warnings
import numpy as np
import pandas as pd
from scipy.optimize import least_squares
from scipy.stats import spearmanr

warnings.filterwarnings("ignore")
np.seterr(all="ignore")

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(os.path.dirname(HERE), "results")
FRONT = os.path.join(RESULTS, "frontiers")
RNG = np.random.default_rng(20261005)
NOISE = 0.02           # nats, the corpora's own log-error noise scale


# ------------------------------------------------------------------ models
def _best(fun, seeds):
    best = None
    for s0 in seeds:
        try:
            r = least_squares(fun, s0, method="lm", max_nfev=8000)
            if best is None or r.cost < best.cost:
                best = r
        except Exception:
            pass
    return best


def fit_floorless(x, S):
    """S = exp(lnA) (x - x0)^beta ;  returns (ln eps predictor, beta, lnA, x0)."""
    def res(th):
        x0 = x.min() - np.exp(th[0])
        return np.log(np.maximum(S, 1e-12)) - (np.exp(th[1]) * np.log(x - x0) + th[2])
    b = _best(res, [[a0, b0, 0.0] for a0 in (-2, 0, 1, 2.5)
                    for b0 in (-1.5, -0.7, 0.0, 0.5)])
    x0 = x.min() - np.exp(b.x[0]); beta = np.exp(b.x[1]); lnA = b.x[2]
    f = lambda xx: -np.exp(lnA + beta * np.log(np.maximum(xx - x0, 1e-9)))
    return f, beta, lnA, x0


def fit_floor(x, y):
    """eps = einf + c exp(-a x) ; y = ln eps."""
    def res(th):
        return np.log(np.exp(th[0]) + np.exp(th[1] - np.exp(th[2]) * x)) - y
    b = _best(res, [[e0, y[0], la] for e0 in (-6, -4, -2.6, -1.6)
                    for la in (-2.0, -1.0, 0.0, 1.0)])
    th = b.x
    f = lambda xx: np.log(np.exp(th[0]) + np.exp(th[1] - np.exp(th[2]) * xx))
    return f, np.exp(th[0])


def fit_both(x, y):
    """eps = einf + c exp(-(a(x-x0))^beta) -- four parameters."""
    def res(th):
        x0 = x.min() - np.exp(th[3])
        bb = 1.0 / (1.0 + np.exp(-th[4]))
        return np.log(np.exp(th[0]) + np.exp(
            th[1] - np.power(np.maximum(np.exp(th[2]) * (x - x0), 1e-12), bb))) - y
    b = _best(res, [[e0, y[0], la, 0.0, bb] for e0 in (-4.0, -1.6)
                    for la in (0.0,) for bb in (-1.0, 1.0)])
    th = b.x; x0 = x.min() - np.exp(th[3]); bb = 1.0 / (1.0 + np.exp(-th[4]))
    f = lambda xx: np.log(np.exp(th[0]) + np.exp(
        th[1] - np.power(np.maximum(np.exp(th[2]) * (xx - x0), 1e-12), bb)))
    return f, np.exp(th[0]), bb


# ------------------------------------------------------- T1: exact identity
def identity_grid():
    rows = []
    for beta in [0.20, 0.30, 0.50, 0.80, 0.95, 1.00]:
        for alpha in [0.4, 1.0, 2.5]:
            for u in [1.5, 4.0, 20.0]:
                S = (alpha * u) ** beta
                s = beta * S / u
                kap = s * (1 - beta) / u
                p0_local = kap / (s * s + kap)
                p0_law = (1 - beta) / ((1 - beta) + beta * S)
                beta_rec = s * s / (s * s + kap * S)
                rows.append(dict(beta=beta, alpha=alpha, u=u, S=S,
                                 p0_local=p0_local, p0_law=p0_law,
                                 err_p0=abs(p0_local - p0_law),
                                 beta_recovered=beta_rec,
                                 err_beta=abs(beta_rec - beta)))
    return pd.DataFrame(rows)


# ------------------------------------------------------ T2: zero-floor null
def zero_floor_null():
    rows = []
    for beta in [0.20, 0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.90, 0.95]:
        shares = []
        for rep in range(12):
            x = np.linspace(2.0, 10.0, 22)
            eps = np.exp(-x ** beta)                 # floor is EXACTLY zero
            y = np.log(eps) + RNG.normal(0, NOISE, x.size)
            _, e0 = fit_floor(x, y)
            shares.append(e0 / eps[-1])
        S_mid = float(np.exp(np.mean(np.log(x ** beta))))
        rows.append(dict(beta=beta, true_floor=0.0,
                         share_median=float(np.median(shares)),
                         share_q10=float(np.quantile(shares, .10)),
                         share_q90=float(np.quantile(shares, .90)),
                         share_predicted=(1 - beta) / ((1 - beta) + beta * S_mid)))
    d = pd.DataFrame(rows)
    d.attrs["spearman"] = spearmanr(d.share_median, d.share_predicted).statistic
    return d


# ------------------------------------------- T3: how many shape parameters
def frontiers():
    for f in sorted(glob.glob(os.path.join(FRONT, "*.csv"))):
        key = os.path.basename(f)[:-4]
        d = pd.read_csv(f)
        res = [c for c in d.columns if c not in ("base", "img_size", "eps")]
        if len(res) != 1 or len(d) < 14:
            continue
        d = d.sort_values(res[0])
        x = np.log(d[res[0]].to_numpy(float))
        eps = d.eps.to_numpy(float)
        yield key, x, eps


def one_dof():
    rows = []
    for key, x, eps in frontiers():
        y = np.log(eps); S = -y
        out = {"frontier": key, "n": len(x)}
        # interior holdout: even indices train, odd test
        tr = np.arange(len(x)) % 2 == 0
        # forward holdout: first 70% train, last 30% test
        cut = int(0.7 * len(x)); tr2 = np.arange(len(x)) < cut
        for tag, mtr in [("int", tr), ("fwd", tr2)]:
            mte = ~mtr
            for nm, fit in [("floorless", lambda m=mtr: fit_floorless(x[m], S[m])[0]),
                            ("floor",     lambda m=mtr: fit_floor(x[m], y[m])[0]),
                            ("both",      lambda m=mtr: fit_both(x[m], y[m])[0])]:
                try:
                    g = fit()
                    out[f"{nm}_{tag}"] = float(np.median(
                        np.abs(np.exp(g(x[mte]) - y[mte]) - 1)))
                except Exception:
                    out[f"{nm}_{tag}"] = np.nan
        _, beta, lnA, x0 = fit_floorless(x, S)
        out["beta"] = beta
        out["lnA"] = lnA
        out["corpus"] = key.split("__")[0]
        out["axis"] = key.split("__", 1)[1] if "__" in key else ""
        out["eps_min"] = eps.min(); out["eps_max"] = eps.max()
        out["in_class"] = bool(0 < beta < 1)
        rows.append(out)
    return pd.DataFrame(rows)


def crossfit():
    rows = []
    truths = [("two-atom  .03+.5e^-.6x", lambda x: 0.03 + 0.5 * np.exp(-0.6 * x), "floor"),
              ("two-atom  .10+.4e^-.4x", lambda x: 0.10 + 0.4 * np.exp(-0.4 * x), "floor"),
              ("shape  exp(-(0.5x)^.6)", lambda x: np.exp(-(0.5 * x) ** 0.6), "floorless"),
              ("shape  exp(-(1.0x)^.8)", lambda x: np.exp(-(1.0 * x) ** 0.8), "floorless")]
    for name, f, kind in truths:
        x = np.linspace(2, 8, 18)
        y = np.log(f(x)) + RNG.normal(0, NOISE, x.size)
        if kind == "floor":
            g, *_ = fit_floorless(x, -y)
        else:
            g, _ = fit_floor(x, y)
        rows.append(dict(truth=name, generating_chart=kind,
                         rms_wrong_chart=float(np.sqrt(np.mean((g(x) - y) ** 2))),
                         noise=NOISE))
    return pd.DataFrame(rows)


# ---------------------------------------------------------- T5: knee depth
def knee_depth(dof):
    d = dof[dof.in_class].copy()
    d["S_star"] = (1 - d.beta) / d.beta
    d["eps_star"] = np.exp(1 - 1 / d.beta)
    d["inside_window"] = (d.eps_star >= d.eps_min) & (d.eps_star <= d.eps_max)
    d["reachable"] = d.eps_star <= d.eps_max
    return d[["frontier", "corpus", "axis", "beta", "S_star", "eps_star",
              "eps_min", "eps_max", "inside_window", "reachable"]]


def eta2(df, val, grp):
    tot = ((df[val] - df[val].mean()) ** 2).sum()
    bet = sum(len(v) * (v.mean() - df[val].mean()) ** 2
              for _, v in df.groupby(grp)[val])
    return bet / tot if tot > 0 else np.nan


