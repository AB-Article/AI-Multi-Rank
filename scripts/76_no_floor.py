    print("  -> results/table_no_floor_identity.csv")

    print("T2  a fitted floor on a frontier whose floor is exactly zero")
    nul = zero_floor_null()
    for _, r in nul.iterrows():
        print(f"    beta={r.beta:.2f}  floor_hat/eps_best = {r.share_median:.3f}"
              f"  [{r.share_q10:.3f},{r.share_q90:.3f}]")
    print(f"    Spearman(measured share, predicted share) = {nul.attrs['spearman']:.3f}")
    print("    the archive's measured median floor share is 0.51 "
          "-> the beta = 0.6 zero-floor value")
    nul.to_csv(os.path.join(RESULTS, "table_no_floor_null.csv"), index=False)
    print("  -> results/table_no_floor_null.csv")

    print("T3  how many shape parameters are identified")
    dof = one_dof()
    summ = []
    for nm, lab, npar in [("floorless", "floorless shape law", 3),
                          ("floor", "two-atom with floor", 3),
                          ("both", "floor + shape index", 4)]:
        summ.append(dict(model=lab, n_par=npar,
                         interior=float(dof[f"{nm}_int"].median()),
                         forward=float(dof[f"{nm}_fwd"].median())))
    summ = pd.DataFrame(summ)
    print(summ.to_string(index=False, float_format=lambda v: f"{v:.4f}"))
    print(f"    the 4th parameter helps on "
          f"{int((dof.both_int < dof.floor_int).sum())}/{len(dof)} frontiers (interior), "
          f"{int((dof.both_fwd < dof.floor_fwd).sum())}/{len(dof)} (forward)")
    print(f"    in-class (0<beta<1): {int(dof.in_class.sum())}/{len(dof)};  "
          f"eta2(corpus) for beta = {eta2(dof,'beta','corpus'):.3f}, "
          f"eta2(axis) = {eta2(dof,'beta','axis'):.3f}")
    dof.to_csv(os.path.join(RESULTS, "table_one_dof_holdout.csv"), index=False)
    summ.to_csv(os.path.join(RESULTS, "table_one_dof_summary.csv"), index=False)
    print("  -> results/table_one_dof_holdout.csv, table_one_dof_summary.csv")

    print("T4  the two charts are indistinguishable at the noise level")
    cf = crossfit()
    print(cf.to_string(index=False, float_format=lambda v: f"{v:.4f}"))
    cf.to_csv(os.path.join(RESULTS, "table_crossfit.csv"), index=False)
    print("  -> results/table_crossfit.csv")

    print("T5  the canonical point as a depth in nats")
    kd = knee_depth(dof)
    print(f"    median beta = {kd.beta.median():.3f}  ->  S* = {kd.S_star.median():.2f} nats, "
          f"eps* = {kd.eps_star.median():.3f}")
    print(f"    eps* reachable on {int(kd.reachable.sum())}/{len(kd)}, "
          f"inside the window on {int(kd.inside_window.sum())}/{len(kd)}")
    kd.to_csv(os.path.join(RESULTS, "table_knee_depth.csv"), index=False)
    print("  -> results/table_knee_depth.csv")
